import 'dart:io';

import 'package:path/path.dart' as p;

/// Marker that every file fully owned by husk_sdk carries near the top.
const String generatedMarker = 'GENERATED by husk_sdk';

/// Where a managed block goes when a file does not contain one yet.
enum InsertAt {
  /// At the end of the file.
  end,

  /// Before the last line that is just `end` (a Ruby podspec's closing
  /// `Pod::Spec.new do ... end`).
  beforeLastRubyEnd,
}

/// One file that `generate` writes or edits.
sealed class PlannedFile {
  PlannedFile(this.path);

  /// Path relative to the project root, POSIX separators.
  final String path;

  /// Computes the new file content from the [existing] content (normalized
  /// to `\n` line endings, or null when the file does not exist).
  ///
  /// Throws [PlanException] when the file cannot be updated safely.
  String apply(String? existing, {required bool force});
}

/// Thrown when a planned edit cannot be applied.
class PlanException implements Exception {
  /// Creates an exception for [path].
  PlanException(this.path, this.message);

  /// File the problem is in.
  final String path;

  /// What is wrong and how to fix it.
  final String message;

  @override
  String toString() => '$path: $message';
}

/// A file husk_sdk owns completely; it carries the generated header.
class OwnedFile extends PlannedFile {
  /// Creates an owned file with its full [content].
  OwnedFile(super.path, this.content);

  /// Full content, `\n` line endings, ending with a newline.
  final String content;

  @override
  String apply(String? existing, {required bool force}) {
    if (existing != null &&
        existing != content &&
        !force &&
        !_head(existing).contains(generatedMarker)) {
      throw PlanException(
        path,
        'exists and was not generated by husk_sdk; move it away or pass '
        '--force to overwrite it',
      );
    }
    return content;
  }

  static String _head(String text) => text.split('\n').take(5).join('\n');
}

/// A block of lines that husk_sdk keeps up to date inside a file the
/// project owns, between `BEGIN husk_sdk` and `END husk_sdk` comments.
class BlockEdit extends PlannedFile {
  /// Creates a block edit.
  BlockEdit(
    super.path, {
    required this.comment,
    required this.body,
    this.insertAt = InsertAt.end,
    this.indent = '',
    this.createIfMissing = false,
    this.requires,
  });

  /// Line comment prefix of the file's language (`//` or `#`).
  final String comment;

  /// Lines between the markers, without [indent].
  final List<String> body;

  /// Where to put the block when the file has none yet.
  final InsertAt insertAt;

  /// Indentation applied to every line of the block.
  final String indent;

  /// Whether to create the file when it does not exist.
  final bool createIfMissing;

  /// A pattern the file must contain before the block can be inserted, with
  /// a message explaining why, e.g. `let package = Package(` in a manifest.
  final (RegExp, String)? requires;

  /// The first marker line.
  String get beginLine =>
      '$indent$comment BEGIN husk_sdk: generated from husk.yaml, do not edit. '
      'Regenerate with `dart run husk_sdk generate`.';

  /// The last marker line.
  String get endLine => '$indent$comment END husk_sdk';

  /// The complete block, markers included.
  List<String> get lines => [
    beginLine,
    for (final l in body) l.isEmpty ? '' : '$indent$l',
    endLine,
  ];

  /// Returns the existing block in [text] (markers included), or null.
  List<String>? find(String text) {
    final all = text.split('\n');
    final range = _range(all);
    return range == null ? null : all.sublist(range.$1, range.$2 + 1);
  }

  (int, int)? _range(List<String> all) {
    int? begin;
    for (var i = 0; i < all.length; i++) {
      final t = all[i].trim();
      if (t.startsWith('$comment BEGIN husk_sdk')) {
        if (begin != null) {
          throw PlanException(path, 'has two BEGIN husk_sdk markers');
        }
        begin = i;
      } else if (t == '$comment END husk_sdk') {
        if (begin == null) {
          throw PlanException(path, 'has END husk_sdk without BEGIN');
        }
        return (begin, i);
      }
    }
    if (begin != null) {
      throw PlanException(path, 'has BEGIN husk_sdk without END husk_sdk');
    }
    return null;
  }

  @override
  String apply(String? existing, {required bool force}) {
    if (existing == null) {
      if (!createIfMissing) {
        throw PlanException(path, 'does not exist');
      }
      return '${lines.join('\n')}\n';
    }
    final all = existing.split('\n');
    final range = _range(all);
    if (range != null) {
      all.replaceRange(range.$1, range.$2 + 1, lines);
      return all.join('\n');
    }
    final req = requires;
    if (req != null && !req.$1.hasMatch(existing)) {
      throw PlanException(path, req.$2);
    }
    switch (insertAt) {
      case InsertAt.end:
        // Drop trailing empty lines, then add one blank line and the block.
        while (all.isNotEmpty && all.last.trim().isEmpty) {
          all.removeLast();
        }
        return [...all, if (all.isNotEmpty) '', ...lines, ''].join('\n');
      case InsertAt.beforeLastRubyEnd:
        final at = all.lastIndexWhere((l) => RegExp(r'^end\s*$').hasMatch(l));
        if (at < 0) {
          throw PlanException(
            path,
            'has no closing `end` line for Pod::Spec.new; add the husk_sdk '
            'block by hand',
          );
        }
        final before = all.sublist(0, at);
        while (before.isNotEmpty && before.last.trim().isEmpty) {
          before.removeLast();
        }
        return [...before, '', ...lines, ...all.sublist(at)].join('\n');
    }
  }
}

/// What happened (or would happen) to one planned file.
enum FileStatus {
  /// Content already matched.
  unchanged,

  /// File was created.
  created,

  /// File was rewritten.
  updated,

  /// The file could not be updated; see [FileOutcome.message].
  failed,
}

/// Result of applying one [PlannedFile].
class FileOutcome {
  /// Creates an outcome.
  FileOutcome(this.path, this.status, [this.message]);

  /// Path relative to the project root.
  final String path;

  /// What happened.
  final FileStatus status;

  /// Error text for [FileStatus.failed].
  final String? message;
}

/// Applies [files] under [root].
///
/// With [dryRun] nothing is written and the outcomes say what would change.
/// Files are only touched when their content changes, so timestamps (and
/// incremental native builds) are left alone on a no-op run. Line endings
/// of an existing file are kept, so a CRLF checkout stays CRLF.
List<FileOutcome> applyPlan(
  String root,
  List<PlannedFile> files, {
  bool dryRun = false,
  bool force = false,
}) {
  final outcomes = <FileOutcome>[];
  for (final planned in files) {
    final file = File(p.joinAll([root, ...p.posix.split(planned.path)]));
    final exists = file.existsSync();
    String? raw;
    if (exists) {
      try {
        raw = file.readAsStringSync();
      } on FileSystemException catch (e) {
        outcomes.add(
          FileOutcome(
            planned.path,
            FileStatus.failed,
            'cannot read: ${e.message}',
          ),
        );
        continue;
      }
    }
    final crlf = raw != null && raw.contains('\r\n');
    final existing = raw?.replaceAll('\r\n', '\n');
    String next;
    try {
      next = planned.apply(existing, force: force);
    } on PlanException catch (e) {
      outcomes.add(FileOutcome(planned.path, FileStatus.failed, e.message));
      continue;
    }
    if (next == existing) {
      outcomes.add(FileOutcome(planned.path, FileStatus.unchanged));
      continue;
    }
    if (!dryRun) {
      file.parent.createSync(recursive: true);
      // writeAsString truncates in place, so an existing file keeps its
      // permissions; new files get the process umask.
      file.writeAsStringSync(crlf ? next.replaceAll('\n', '\r\n') : next);
    }
    outcomes.add(
      FileOutcome(
        planned.path,
        exists ? FileStatus.updated : FileStatus.created,
      ),
    );
  }
  return outcomes;
}
